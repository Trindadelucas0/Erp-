import { beforeEach, describe, expect, it, vi } from 'vitest'
import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import type { ReactNode } from 'react'
import Pagina from '@/app/auditoria-entradas/[id]/precificacao/page'
vi.mock('next/navigation', () => ({ useParams: () => ({ id: 'n' }) }))
vi.mock('@/components/compartilhado/proteger-rota', () => ({ ProtegerRota: ({ children }: { children: ReactNode }) => children }))
vi.mock('@/hooks/use-permissao', () => ({ usePermissao: () => mocks.podeGravar }))
const mocks = vi.hoisted(() => ({ get: vi.fn(), put: vi.fn(), post: vi.fn(), podeGravar: true }))
vi.mock('@/services/api', () => ({ clienteHttp: mocks }))
const item = { itemId: 'i1', nItem: 1, descricao: 'Produto', produtoId: 'p', produtoNome: 'Produto', sku: '001', vinculado: true,
  base: { precoTabela: 100, desconto: 0, ipi: 0, outras: 0, frete: 0, tipoFrete: '1', transporteSimples: false, st: 0, creditoIcms: 0, creditoIcmsFrete: 0, creditoPisCofins: 0 },
  revisao: 0, origem: 'origem-teste', parametros: { ajustes: {}, margemPercentual: 0, margemAtacado: null }, precoAtual: 90, precoAtacadoAtual: null, estoqueDisponivel: 12 }
const grade = { nota: { id: 'n', chaveNfe: '', nomeEmitente: 'Fornecedor teste', dataEmissao: null }, regrasFiscais: { mercadoria: { modo: 'nota', aliquota: null }, transporte: { modo: 'nota', aliquota: null } }, ajustesCusto: { decisaoFrete: null, bases: [], despesas: [] }, basesCusto: [], residuaisCusto: [], pendenciasCusto: [], parametrizacaoCadastrada: true, parametrizacao: { totalVenda: 0 }, encargosPercentual: 0, itens: [item] }
describe('Precificação simplificada', () => {
  beforeEach(() => { vi.resetAllMocks(); mocks.podeGravar = true; vi.stubGlobal('ResizeObserver', class { observe() {} unobserve() {} disconnect() {} }); mocks.get.mockResolvedValue({ data: grade }) })
  it('permite gravar diretamente e preserva campos após erro', async () => {
    mocks.put.mockRejectedValue(new Error('O custo mudou'))
    render(<Pagina />)
    const margem = await screen.findByLabelText('Margem % do item 1')
    fireEvent.change(margem, { target: { value: '10' } })
    expect(screen.getByRole('button', { name: 'Gravar preços válidos' })).not.toBeDisabled()
    for (const texto of ['Formação de custo', 'Histórico de memórias', 'Memórias confirmadas', 'Memória', 'Confirmar custos válidos']) expect(screen.queryByText(texto)).not.toBeInTheDocument()
    expect(mocks.post).not.toHaveBeenCalled()
    expect(margem).toHaveValue('10')
    fireEvent.click(screen.getByRole('button', { name: 'Gravar preços válidos' }))
    await waitFor(() => expect(mocks.put).toHaveBeenCalledWith('/entrada-notas/n/precificacao', expect.objectContaining({ itens: [expect.objectContaining({ itemId: 'i1', produtoId: 'p', margemPercentual: 10 })] })))
    expect(await screen.findByText('O custo mudou')).toBeTruthy()
    expect(margem).toHaveValue('10')
  })
  it('produto repetido só grava a linha explicitamente selecionada', async () => {
    mocks.get.mockResolvedValue({ data: { ...grade, itens: [{ ...item, estadoCusto: 'confirmado' }, { ...item, itemId: 'i2', nItem: 2, estadoCusto: 'confirmado' }] } })
    mocks.put.mockResolvedValue({ data: grade })
    render(<Pagina />)
    const escolhas = await screen.findAllByLabelText('Usar esta linha para o preço')
    expect(screen.getByRole('button', { name: 'Gravar preços válidos' })).toBeDisabled()
    fireEvent.click(escolhas[1])
    fireEvent.click(screen.getByRole('button', { name: 'Gravar preços válidos' }))
    await waitFor(() => expect(mocks.put).toHaveBeenCalledWith('/entrada-notas/n/precificacao', expect.objectContaining({ itens: [expect.objectContaining({ itemId: 'i2' })] })))
  })
  it('adicionais começam fechados e cada produto expande de forma independente', async () => {
    mocks.get.mockResolvedValue({ data: { ...grade, itens: [item, { ...item, itemId: 'i2', produtoId: 'p2', nItem: 2 }] } })
    render(<Pagina />)
    const secoes = await screen.findAllByText('Campos adicionais')
    const primeiro = secoes[0].closest('details')!, segundo = secoes[1].closest('details')!
    expect(primeiro).not.toHaveAttribute('open')
    expect(segundo).not.toHaveAttribute('open')
    fireEvent.click(secoes[0])
    expect(primeiro).toHaveAttribute('open')
    expect(segundo).not.toHaveAttribute('open')
  })
  it('descontos e adicionais recalculam ambos os preços mantendo margens independentes', async () => {
    render(<Pagina />)
    const margem = await screen.findByLabelText('Margem % do item 1')
    fireEvent.change(margem, { target: { value: '20' } })
    fireEvent.change(screen.getByLabelText('Margem atacado % do item 1'), { target: { value: '10' } })
    fireEvent.change(screen.getByLabelText('% Desc. do item 1'), { target: { value: '10' } })
    fireEvent.change(screen.getByLabelText('% Desc. destaque do item 1'), { target: { value: '5' } })
    expect(screen.getByLabelText('Preço de venda do item 1')).toHaveValue('106.875')
    expect(screen.getByLabelText('Preço atacado do item 1')).toHaveValue('95')
    expect(margem).toHaveValue('20')
    fireEvent.change(screen.getByLabelText('Preço atacado do item 1'), { target: { value: '100' } })
    expect(screen.getByLabelText('Margem atacado % do item 1')).toHaveValue('14.5')
    expect(screen.getByLabelText('Preço de venda do item 1')).toHaveValue('106.875')
  })
  it('alternar frete e adicional entre percentual e reais não duplica componentes', async () => {
    render(<Pagina />)
    await screen.findByLabelText('Margem % do item 1')
    fireEvent.change(screen.getByLabelText('% Frete do item 1'), { target: { value: '10' } })
    expect(screen.getByLabelText('Valor frete do item 1')).toHaveValue('10')
    fireEvent.change(screen.getByLabelText('Valor frete do item 1'), { target: { value: '5' } })
    expect(screen.getByLabelText('% Frete do item 1')).toHaveValue('5')
    fireEvent.change(screen.getByLabelText('% Custo adicional do item 1'), { target: { value: '10' } })
    expect(screen.getByLabelText('Valor adicional do item 1')).toHaveValue('10.5')
    fireEvent.change(screen.getByLabelText('Valor adicional do item 1'), { target: { value: '5' } })
    expect(screen.getByLabelText('Preço de venda do item 1')).toHaveValue('110')
  })
  it('valida a simulação no servidor ao sair do campo, sem gravar preços', async () => {
    mocks.post.mockResolvedValue({ data: { erro: null, origem: item.origem } })
    render(<Pagina />)
    const margem = await screen.findByLabelText('Margem % do item 1')
    fireEvent.change(margem, { target: { value: '20' } })
    fireEvent.blur(margem)
    await waitFor(() => expect(mocks.post).toHaveBeenCalledWith('/entrada-notas/n/precificacao/simular', { itemId: 'i1', ajustes: {}, margemPercentual: 20, margemAtacado: null }))
    expect(mocks.put).not.toHaveBeenCalled()
  })
  it('bloqueia números vazios, desconto inválido e carga maior que 100%', async () => {
    render(<Pagina />)
    const margem = await screen.findByLabelText('Margem % do item 1')
    const gravar = screen.getByRole('button', { name: 'Gravar preços válidos' })
    fireEvent.change(margem, { target: { value: '100' } })
    expect(gravar).toBeDisabled()
    fireEvent.change(margem, { target: { value: '20' } })
    fireEvent.change(screen.getByLabelText('% Desc. do item 1'), { target: { value: '101' } })
    expect(gravar).toBeDisabled()
    fireEvent.change(screen.getByLabelText('% Desc. do item 1'), { target: { value: '' } })
    expect(gravar).toBeDisabled()
    expect(screen.getByLabelText('% Desc. do item 1')).toHaveValue('')
  })
  it('grava revisão, parâmetros e atacado e recupera os valores salvos', async () => {
    mocks.put.mockResolvedValue({ data: { ...grade, itens: [{ ...item, revisao: 1, precoAtual: 125, precoAtacadoAtual: 111.1111, parametros: { ajustes: {}, margemPercentual: 20, margemAtacado: 10 } }] } })
    render(<Pagina />)
    fireEvent.change(await screen.findByLabelText('Margem % do item 1'), { target: { value: '20' } })
    fireEvent.change(screen.getByLabelText('Margem atacado % do item 1'), { target: { value: '10' } })
    fireEvent.click(screen.getByRole('button', { name: 'Gravar preços válidos' }))
    await waitFor(() => expect(mocks.put).toHaveBeenCalledWith('/entrada-notas/n/precificacao', expect.objectContaining({ itens: [expect.objectContaining({ ajustes: {}, origem: item.origem, revisao: 0, precoVenda: 125, precoAtacado: 111.1111 })] })))
    await screen.findByRole('status')
    expect(screen.getByLabelText('Margem atacado % do item 1')).toHaveValue('10')
  })
  it('usuário sem permissão consulta, mas não edita nem grava', async () => {
    mocks.podeGravar = false
    render(<Pagina />)
    expect(await screen.findByLabelText('Margem % do item 1')).toBeDisabled()
    expect(screen.getByLabelText('Preço atacado do item 1')).toBeDisabled()
    expect(screen.getByLabelText('Preço tabela do item 1')).toBeDisabled()
    expect(screen.getByRole('button', { name: 'Gravar preços válidos' })).toBeDisabled()
  })
  it('não permite gravar produto não vinculado', async () => {
    mocks.get.mockResolvedValue({ data: { ...grade, itens: [{ ...item, produtoId: null, vinculado: false }] } })
    render(<Pagina />)
    expect(await screen.findByLabelText('Margem % do item 1')).toBeDisabled()
    expect(screen.getByText('Sem produto vinculado.')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Gravar preços válidos' })).toBeDisabled()
  })
  it('não aplica resposta antiga de simulação depois de nova edição', async () => {
    let responder!: (valor: unknown) => void
    mocks.post.mockReturnValue(new Promise(resolve => { responder = resolve }))
    render(<Pagina />)
    const margem = await screen.findByLabelText('Margem % do item 1')
    fireEvent.blur(margem)
    fireEvent.change(margem, { target: { value: '20' } })
    responder({ data: { erro: 'Resposta antiga', origem: item.origem } })
    await waitFor(() => expect(mocks.post).toHaveBeenCalledOnce())
    expect(screen.queryByText('Resposta antiga')).not.toBeInTheDocument()
    expect(margem).toHaveValue('20')
  })
  it('erro em uma linha não descarta sua edição ao gravar as outras', async () => {
    const segunda = { ...item, itemId: 'i2', produtoId: 'p2', nItem: 2 }
    mocks.get.mockResolvedValue({ data: { ...grade, itens: [item, segunda] } })
    mocks.put.mockResolvedValue({ data: { ...grade, itens: [{ ...item, revisao: 1 }, segunda] } })
    render(<Pagina />)
    fireEvent.change(await screen.findByLabelText('Margem % do item 2'), { target: { value: '100' } })
    fireEvent.click(screen.getByRole('button', { name: 'Gravar preços válidos' }))
    await screen.findByRole('status')
    expect(screen.getByLabelText('Margem % do item 2')).toHaveValue('100')
    expect(mocks.put.mock.calls[0][1].itens).toHaveLength(1)
  })
  it('mostra estado vazio sem permitir gravar', async () => {
    mocks.get.mockResolvedValue({ data: { ...grade, itens: [] } })
    render(<Pagina />)
    expect(await screen.findByText('Nenhum item nesta nota.')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Gravar preços válidos' })).toBeDisabled()
  })
})
